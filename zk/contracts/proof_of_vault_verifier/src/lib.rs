#[cfg(test)]
mod test {
    use super::*;
    use soroban_sdk::testutils::Address as _;
    use soroban_sdk::Env;

    fn dummy_g1(env: &Env) -> BytesN<96> {
        // BLS12-381 G1 generator point (uncompressed big-endian x || y)
        BytesN::from_array(env, &[
            0x17, 0xf1, 0xd3, 0xa7, 0x31, 0x97, 0xd7, 0x94,
            0x26, 0x95, 0x63, 0x8c, 0x4f, 0xa9, 0xac, 0x0f,
            0xc3, 0x68, 0x8c, 0x4f, 0x97, 0x74, 0xb9, 0x05,
            0xa1, 0x4e, 0x3a, 0x3f, 0x17, 0x1b, 0xac, 0x58,
            0x6c, 0x55, 0xe8, 0x3f, 0xf9, 0x7a, 0x1a, 0xef,
            0xfb, 0x3a, 0xf0, 0x0a, 0xdb, 0x22, 0xc6, 0xbb,
            0x08, 0xb3, 0xf4, 0x81, 0xe3, 0xaa, 0xa0, 0xf1,
            0xa0, 0x9e, 0x30, 0xed, 0x74, 0x1d, 0x8a, 0xe4,
            0xfc, 0xf5, 0xe0, 0x95, 0xd5, 0xd0, 0x0a, 0xf6,
            0x00, 0x01, 0xd3, 0x80, 0x88, 0x03, 0x57, 0x5f,
            0xf0, 0x4f, 0x9f, 0x1c, 0x8f, 0xa2, 0x5c, 0x27,
            0x42, 0x57, 0x26, 0x89, 0x7f, 0x0a, 0x54, 0x02,
        ])
    }

    fn make_vk(env: &Env, g1: BytesN<96>) -> VerificationKey {
        VerificationKey {
            alpha: g1.clone(),
            beta:  BytesN::from_array(env, &[0u8; 192]),
            gamma: BytesN::from_array(env, &[0u8; 192]),
            delta: BytesN::from_array(env, &[0u8; 192]),
            ic_0:  g1.clone(),
            ic_1:  g1.clone(),
        }
    }

    #[test]
    fn test_constructor() {
        let env = Env::default();
        env.mock_all_auths();
        let admin = Address::generate(&env);
        let g1 = dummy_g1(&env);
        let vk = make_vk(&env, g1);
        // soroban-sdk 22: register passes constructor args at deploy time
        let contract_id = env.register(ProofOfVaultVerifier, (admin.clone(), vk.clone()));
        // Verify VK was stored by constructor
        let stored_vk: VerificationKey = env.as_contract(&contract_id, || {
            env.storage().instance().get(&DataKey::Vk).unwrap()
        });
        assert_eq!(stored_vk.alpha, vk.alpha);
    }
}
